/** Hex for the few browsers without OKLCH, derived from the default palette. */
function fallbackCss() {
  const palette = derivePalette(profiles[DEFAULT_THEME].spec, "light");
  const hex = (value) =>
    `#${toSrgb(parseColor(value)).map((channel) => Math.round(channel * 255).toString(16).padStart(2, "0")).join("")}`;
  const lines = Object.entries(palette).map(([token, value]) => `    --ml-${token}: ${hex(value)};`);
  return `@supports not (color: oklch(0 0 0)) {
  :root {
${lines.join("\n")}
  }
}`;
}

/**
 * Every canonical theme, rendered from its spec through the same function a
 * project theme or a Studio theme uses. The default theme also owns `:root`.
 */
export function renderTokensCss() {
  const themes = Object.entries(profiles).map(([id, profile]) =>
    renderSpecCss(profile.spec, { root: id === DEFAULT_THEME, aliases: profile.aliases, banner: false }),
  );
  return `/* Generated by @mlola-ui/engine from the canonical theme specs. Do not hand edit. */
${renderScaleCss()}

${themes.join("\n")}
${fallbackCss()}`;
}

