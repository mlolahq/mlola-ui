export function renderDtcg() {
  const dtcgColor = (value) => {
    const match = value.match(/^oklch\(([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+))?\)$/);
    if (!match) return value;
    return {
      colorSpace: "oklch",
      components: match.slice(1, 4).map(Number),
      alpha: match[4] === undefined ? 1 : Number(match[4]),
    };
  };
  const output = {
    $schema: "https://tr.designtokens.org/format/",
    $description: "Generated Mlola UI theme tokens. Values use the DTCG 2025.10 format.",
    theme: {
      $description: "Theme vector dimensions normalized to [0,1].",
      dimensions: Object.fromEntries(dimensions.map(([name, low, high], index) => [
        name,
        {
          $type: "number",
          $value: index,
          $description: `${low} (0) → ${high} (1)`,
          $extensions: { "com.mlola.axis": { low, high } },
        },
      ])),
      coupling: Object.fromEntries(Object.entries(coupling).map(([name, value]) => [name, { $type: "number", $value: value }])),
    },
    profile: {},
  };

  for (const [name, profile] of Object.entries(profiles)) {
    const derived = derive(profile);
    const fonts = resolveFonts(profile.spec.fonts);
    output.profile[name] = {
      $description: `${profile.label} theme profile, derived from its spec.`,
      $extensions: { "com.mlola.spec": profile.spec },
      vector: {
        $description: "Ordered τ vector is available in the com.mlola.vector extension.",
        $extensions: { "com.mlola.vector": profile.vector },
        ...Object.fromEntries(dimensions.map(([dimension], index) => [dimension, { $type: "number", $value: profile.vector[index] }])),
      },
      light: Object.fromEntries(Object.entries(derivePalette(profile.spec, "light")).map(([token, value]) => [token, { $type: "color", $value: dtcgColor(value) }])),
      dark: Object.fromEntries(Object.entries(derivePalette(profile.spec, "dark")).map(([token, value]) => [token, { $type: "color", $value: dtcgColor(value) }])),
      geometry: {
        radius: { $type: "dimension", $value: { value: round(derived.radius), unit: "px" } },
        border: { $type: "dimension", $value: { value: derived.border >= 1.4 ? 1.5 : 1, unit: "px" } },
        control: { $type: "dimension", $value: { value: round(derived.controlHeight, 4), unit: "rem" } },
        targetMin: { $type: "dimension", $value: { value: 44, unit: "px" } },
      },
      motion: {
        fast: { $type: "duration", $value: { value: Math.round(derived.durationFast), unit: "ms" } },
        normal: { $type: "duration", $value: { value: Math.round(derived.durationNormal), unit: "ms" } },
        slow: { $type: "duration", $value: { value: Math.round(derived.durationSlow), unit: "ms" } },
        reveal: { $type: "duration", $value: { value: Math.round(derived.durationReveal), unit: "ms" } },
        easing: { $type: "cubicBezier", $value: [0.2, 0, 0, 1] },
        $extensions: {
          "com.mlola.spring": {
            omega: round(derived.springOmega, 3),
            damping: round(derived.springDamping, 3),
            bounceDamping: round(derived.springBounceDamping, 3),
            spring: springEasing({ omega: derived.springOmega, damping: derived.springDamping }),
            bounce: springEasing(
              { omega: derived.springOmega, damping: derived.springBounceDamping },
              28,
            ),
          },
        },
      },
      typography: {
        body: {
          $type: "typography",
          $value: {
            fontFamily: (fonts.sans.match(/"([^"]+)"/)?.[1] ?? fonts.sans.split(",")[0]).trim(),
            fontSize: { value: 16, unit: "px" },
            fontWeight: 400,
            letterSpacing: { value: round(derived.tracking, 4), unit: "em" },
            lineHeight: round(derived.bodyLeading),
          },
        },
      },
    };
  }
  return output;
}
